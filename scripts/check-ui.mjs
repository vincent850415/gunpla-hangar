import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
await fs.mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true });
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    return url.origin === 'http://127.0.0.1:4173' || ['data:', 'blob:'].includes(url.protocol) ? route.continue() : route.abort();
  });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', err => errors.push(err.message));
  const remote = []; context.on('request', req => { if (new URL(req.url()).origin !== 'http://127.0.0.1:4173' && !req.url().startsWith('data:') && !req.url().startsWith('blob:')) remote.push(req.url()); });
  await page.goto('http://127.0.0.1:4173');
  await page.getByText('已儲存至這台裝置', { exact: true }).waitFor();
  await page.screenshot({ path: 'test-results/desktop-empty.png', fullPage: true });
  const original = await fs.readFile('public/sample.jpg');
  // Appending a JPEG end marker keeps the same visual content with a different file hash.
  await fs.writeFile('test-results/batch-sample.jpg', Buffer.concat([original, Buffer.from([0xff, 0xd9])]));
  await page.locator('input[type=file][multiple]').setInputFiles(['public/sample.jpg', 'test-results/batch-sample.jpg']);
  await page.getByRole('status').filter({ hasText: '新增 2 筆' }).waitFor({ timeout: 180000 });
  assert.equal(await page.locator('.record').count(), 2);
  await page.locator('.record').first().click();
  const name = await page.getByLabel('商品名稱', { exact: false }).inputValue();
  const series = await page.locator('.editor').getByLabel('作品系列', { exact: false }).inputValue();
  const grade = await page.locator('.editor-fields select').inputValue();
  const scale = await page.getByLabel('比例', { exact: true }).inputValue();
  console.log('Real attachment OCR:', JSON.stringify({ name, series, grade, scale }));
  await fs.writeFile('test-results/ocr-evidence.txt', await page.locator('.editor pre').textContent());
  await page.screenshot({ path: 'test-results/editor.png', fullPage: true });
  assert.equal(name, 'RX-78-2 GUNDAM'); assert.equal(series, 'HGUC 宇宙世紀'); assert.equal(grade, 'HG'); assert.equal(scale, '1/144');
  assert.match(await page.locator('.editor details').textContent(), /PaddleOCR PP-OCRv6/);
  await page.getByLabel('購入價格').fill('450'); await page.getByLabel('存放位置', { exact: true }).fill('書房 A 櫃第 2 層');
  await page.getByRole('button', { name: '確認並儲存' }).click();
  await page.getByText('已儲存至這台裝置', { exact: true }).waitFor();
  await page.reload(); await page.locator('.record .confirmed').waitFor();
  // Re-recognition is a candidate only: retain the saved price, position and
  // confirmation until the user explicitly adopts and saves new fields.
  await page.locator('.record').first().click();
  await page.getByRole('button', { name: '重新辨識', exact: true }).click();
  await page.locator('.comparison-modal').waitFor({ timeout: 180000 });
  assert.equal(await page.locator('.comparison-modal input:checked').count(), 0);
  await page.screenshot({ path: 'test-results/real-ocr-comparison.png', fullPage: true });
  await page.getByRole('button', { name: '保留目前值', exact: true }).click();
  assert.equal(await page.getByLabel('購入價格').inputValue(), '450');
  assert.equal(await page.getByLabel('存放位置', { exact: true }).inputValue(), '書房 A 櫃第 2 層');
  await page.getByRole('button', { name: '關閉編輯', exact: true }).click();
  assert.equal(await page.locator('.record .confirmed').count(), 1);
  await page.getByRole('button', { name: '手動新增' }).click();
  await page.getByLabel('商品名稱', { exact: false }).fill('GUNDAM AERIAL');
  await page.locator('.editor').getByLabel('作品系列', { exact: false }).fill('水星的魔女');
  await page.locator('.editor-fields select').selectOption('HG');
  await page.getByLabel('比例', { exact: true }).fill('1/144');
  await page.getByRole('button', { name: '確認並儲存' }).click();
  const downloadEvent = page.waitForEvent('download'); await page.getByRole('button', { name: '匯出 Excel', exact: true }).click(); await page.screenshot({ path: 'test-results/export-preview.png', fullPage: true }); await page.getByRole('button', { name: '下載 Excel', exact: true }).click();
  const downloaded = await downloadEvent; const exportPath = 'test-results/smoke-export.xlsx'; await downloaded.saveAs(exportPath);
  const workbook = new ExcelJS.Workbook(); await workbook.xlsx.readFile(exportPath);
  assert.deepEqual(workbook.worksheets.map(s => s.name).sort(), ['HGUC 宇宙世紀', '水星的魔女'].sort());
  assert.equal(workbook.getWorksheet('HGUC 宇宙世紀').getCell('C2').value, 450);
  assert.equal(workbook.getWorksheet('HGUC 宇宙世紀').getCell('D2').value, '書房 A 櫃第 2 層');
  assert.equal(workbook.getWorksheet('水星的魔女').getCell('C2').value, null);
  await page.screenshot({ path: 'test-results/desktop-populated.png', fullPage: true });
  await page.locator('input[type=file][multiple]').setInputFiles('public/sample.jpg');
  await page.getByRole('status').filter({ hasText: '略過 1 張重複照片' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 }); await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile must not overflow horizontally');
  await page.locator('.record').first().click();
  await page.screenshot({ path: 'test-results/mobile-editor.png', fullPage: true });
  await page.getByRole('button', { name: '關閉編輯' }).click();
  const backupEvent = page.waitForEvent('download'); await page.getByRole('button', { name: '備份收藏', exact: true }).click();
  const backupDownload = await backupEvent; await backupDownload.saveAs('test-results/backup.json');
  const backupRecords = JSON.parse(await fs.readFile('test-results/backup.json', 'utf8')).records;
  assert.equal(backupRecords.filter(r => r.productLine === 'HGUC').length, 2);
  const freshContext = await browser.newContext();
  const freshPage = await freshContext.newPage(); await freshPage.goto('http://127.0.0.1:4173');
  await freshPage.getByText('已儲存至這台裝置', { exact: true }).waitFor();
  await freshPage.locator('input[type=file]:not([multiple])').setInputFiles('test-results/backup.json');
  await freshPage.locator('.restore-modal').waitFor(); await freshPage.getByRole('radio', { name: /作為外部資料匯入/ }).check(); await freshPage.screenshot({ path: 'test-results/restore-preview.png', fullPage: true }); await freshPage.getByRole('button', { name: '確認合併還原', exact: true }).click(); await freshPage.getByRole('status').filter({ hasText: '已還原 3 筆' }).waitFor();
  assert.equal(await freshPage.locator('.record').count(), 3);
  assert.equal(await freshPage.locator('.record .confirmed').count(), 0);
  await freshPage.locator('.record').nth(1).click();
  assert.equal(await freshPage.locator('.editor').getByLabel('作品系列', { exact: false }).inputValue(), 'HGUC 宇宙世紀');
  await freshPage.getByRole('button', { name: '確認並儲存' }).click();
  await freshPage.locator('.record').nth(1).click();
  assert.equal(await freshPage.locator('.editor').getByLabel('作品系列', { exact: false }).inputValue(), 'HGUC 宇宙世紀');
  await freshPage.getByRole('button', { name: '關閉編輯' }).click();
  await freshPage.getByRole('button', { name: '手動新增' }).click();
  await freshPage.getByRole('button', { name: '確認並儲存' }).click();
  await freshPage.getByRole('alert').filter({ hasText: '請填寫商品名稱' }).waitFor();
  await freshContext.close();
  // The app and OCR remain usable with all external network requests blocked.
  assert.deepEqual(remote, []); assert.deepEqual(errors, []);
  console.log('PASS: batch actual-image OCR, editing, persistence, multi-series XLSX download/readback, exclusion of unconfirmed rows, duplicate skip, backup restore, form validation, mobile layout, no external network requests.');
} finally { await browser.close(); }
